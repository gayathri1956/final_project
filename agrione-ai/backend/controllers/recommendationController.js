const { recommend } = require('../ml/crop_recommendation/service');
const Prediction = require('../models/Prediction');

exports.getRecommendation = async (req, res) => {
  try {
    const inputs = req.body;
    const results = recommend(inputs);

    // Save prediction
    await Prediction.create({
      user: req.user._id,
      farm: inputs.farmId || undefined,
      type: 'crop_recommendation',
      inputs,
      result: { recommendations: results },
      confidence: results.length > 0 ? results[0].confidence : 0,
      isBaseline: true,
    });

    res.json({
      success: true,
      recommendations: results,
      disclaimer: 'These recommendations are generated by a baseline rule-based system. For best results, consult local agricultural experts.',
    });
  } catch (error) {
    res.status(500).json({ success: false, message: 'Failed to generate recommendation.' });
  }
};
